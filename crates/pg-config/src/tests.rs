#[test]
fn signed_config_roundtrip_and_tamper_rejection() {
    let seed = [0x42u8; 32];
    let pk = public_key_from_seed(&seed);
    let backends = [
        BackendSpec { ipv4: [127, 0, 0, 1], port: 19001 },
        BackendSpec { ipv4: [127, 0, 0, 1], port: 19002 },
    ];
    let routes = [
        Route {
            method: Method::Get,
            pattern: Pattern::Exact(b"/health"),
            action: Action::Health,
        },
        Route {
            method: Method::Post,
            pattern: Pattern::Exact(b"/api/chat"),
            action: Action::Forward {
                backend: BackendId(0),
                max_body: 1048576,
            },
        },
        Route {
            method: Method::Get,
            pattern: Pattern::Prefix(b"/game/"),
            action: Action::Forward {
                backend: BackendId(1),
                max_body: 0,
            },
        },
    ];

    let mut buf = [0u8; 512];
    let len = encode_and_sign(&backends, &routes, &seed, &mut buf).unwrap();
    let cfg = verify_and_parse(&buf[..len], &pk).unwrap();
    assert_eq!(cfg.backends(), &backends);
    assert_eq!(cfg.routes().len(), 3);

    // Wrong public key is rejected
    let wrong_pk = public_key_from_seed(&[0x99u8; 32]);
    assert_eq!(
        verify_and_parse(&buf[..len], &wrong_pk).unwrap_err(),
        ConfigError::BadSignature
    );

    // Every single-byte tamper in payload or signature is rejected
    for i in 0..len {
        let mut tampered = buf;
        tampered[i] ^= 0x01;
        assert!(
            verify_and_parse(&tampered[..len], &pk).is_err(),
            "accepted tampered byte at {i}"
        );
    }
}

#[test]
fn openssl_signed_artifacts_verify() {
    let sconf = include_bytes!("../../../config/sel4/proxy.sconf");
    let parsed = verify_and_parse(sconf, &PUBLIC_KEY).expect("valid sel4 proxy.sconf");
    assert_eq!(parsed.n_backends, 2);
    assert_eq!(parsed.n_routes, 6);

    let dev_conf = include_bytes!("../../../config/dev/proxy.conf");
    let dev_sig_hex = include_bytes!("../../../config/dev/proxy.conf.sig");
    let dev_sig = parse_hex_sig(dev_sig_hex).expect("valid hex sig");
    assert!(verify_ed25519(&PUBLIC_KEY, dev_conf, &dev_sig));
}

